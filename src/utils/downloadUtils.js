/**
 * Palette Export and File Download Utilities for Chromapick
 * Uses native Blob and object URLs with automatic resource cleanup.
 */

import { hexToRgb, rgbToHsl, getRelativeLuminance } from './colorMath';

/**
 * Triggers a file download using Blob and revokes object URL
 */
export function triggerFileDownload(content, filename, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Generates JSON export format
 */
export function exportPaletteJson(paletteName, colors) {
  const formatted = {
    name: paletteName || 'Chromapick Palette',
    generator: 'Chromapick — Image Color Extractor & Palette Studio',
    exportedAt: new Date().toISOString(),
    colors: colors.map((c, idx) => {
      const hex = typeof c === 'string' ? c : c.hex;
      const rgb = hexToRgb(hex);
      const hsl = rgbToHsl(rgb.r, rgb.g, rgb.b);
      return {
        id: idx + 1,
        hex: hex.toUpperCase(),
        rgb,
        hsl,
        luminance: Number(getRelativeLuminance(rgb.r, rgb.g, rgb.b).toFixed(4)),
        frequency: c.frequency !== undefined ? c.frequency : undefined
      };
    })
  };
  return JSON.stringify(formatted, null, 2);
}

/**
 * Generates CSS Variables export format
 */
export function exportPaletteCssVariables(paletteName, colors) {
  const lines = [
    `/* ${paletteName || 'Chromapick Palette'} */`,
    `/* Generated by Chromapick */`,
    `:root {`
  ];
  colors.forEach((c, idx) => {
    const hex = (typeof c === 'string' ? c : c.hex).toUpperCase();
    lines.push(`  --color-${idx + 1}: ${hex};`);
  });
  lines.push(`}`);
  return lines.join('\n');
}

