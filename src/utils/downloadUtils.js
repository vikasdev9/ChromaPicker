/**
 * Generates Adobe Swatch Exchange (ASE) binary format Blob
 */
export function exportPaletteAse(paletteName, colors) {
  const hexList = colors.map(c => typeof c === 'string' ? c : c.hex);
  const count = hexList.length;

  const nameLen = 8; // e.g. '#FFD814' (7 chars) + 1 null char = 8
  const blockDataLen = 2 + nameLen * 2 + 4 + 12 + 2; // 36 bytes
  const blockSize = 6 + blockDataLen; // 42 bytes
  const totalBytes = 12 + count * blockSize;

  const buffer = new ArrayBuffer(totalBytes);
  const view = new DataView(buffer);

  // Magic header: 'ASEF'
  view.setUint8(0, 0x41);
  view.setUint8(1, 0x53);
  view.setUint8(2, 0x45);
  view.setUint8(3, 0x46);

  // Version 1.0
  view.setUint16(4, 1, false);
  view.setUint16(6, 0, false);

  // Number of blocks
  view.setUint32(8, count, false);

  let offset = 12;
  hexList.forEach((hex) => {
    const cleanHex = hex.toUpperCase();
    const rgb = hexToRgb(cleanHex);

    // Block type: 0x0001 (Color entry)
    view.setUint16(offset, 0x0001, false);
    offset += 2;

    // Block length
    view.setUint32(offset, blockDataLen, false);
    offset += 4;

    // Name length (characters count including null)
    view.setUint16(offset, nameLen, false);
    offset += 2;

    // Name UTF-16BE
    for (let i = 0; i < cleanHex.length; i++) {
      view.setUint16(offset, cleanHex.charCodeAt(i), false);
      offset += 2;
    }
    // Null terminator
    view.setUint16(offset, 0, false);
    offset += 2;

    // Color model: 'RGB '
    view.setUint8(offset, 0x52);     // 'R'
    view.setUint8(offset + 1, 0x47); // 'G'
    view.setUint8(offset + 2, 0x42); // 'B'
    view.setUint8(offset + 3, 0x20); // ' '
    offset += 4;

    // RGB floats
    view.setFloat32(offset, rgb.r / 255, false);
    offset += 4;
    view.setFloat32(offset, rgb.g / 255, false);
    offset += 4;
    view.setFloat32(offset, rgb.b / 255, false);
    offset += 4;

    // Color type: 0 = Global
    view.setUint16(offset, 0, false);
    offset += 2;
  });

  return new Blob([buffer], { type: 'application/octet-stream' });
}

