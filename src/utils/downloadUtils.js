/**
 * Generates GIMP / Inkscape GPL palette format
 */
export function exportPaletteGpl(paletteName, colors) {
  const lines = [
    'GIMP Palette',
    `Name: ${paletteName || 'Chromapick Palette'}`,
    'Columns: 4',
    '# Generated by Chromapick',
    '#'
  ];
  colors.forEach((c, idx) => {
    const hex = typeof c === 'string' ? c : c.hex;
    const rgb = hexToRgb(hex);
    const r = String(rgb.r).padStart(3, ' ');
    const g = String(rgb.g).padStart(3, ' ');
    const b = String(rgb.b).padStart(3, ' ');
    lines.push(`${r} ${g} ${b}  Color ${idx + 1}`);
  });
  return lines.join('\n');
}

/**
 * Generates an SVG swatch graphic string
 */
export function exportPaletteSvg(paletteName, colors) {
  const swatchWidth = 120;
  const swatchHeight = 160;
  const padding = 20;
  const totalWidth = colors.length * swatchWidth + (colors.length - 1) * 12 + padding * 2;
  const totalHeight = swatchHeight + padding * 2 + 50;

  const rects = colors.map((c, idx) => {
    const hex = (typeof c === 'string' ? c : c.hex).toUpperCase();
    const x = padding + idx * (swatchWidth + 12);
    const y = padding + 40;
    return `
      <g>
        <rect x="${x}" y="${y}" width="${swatchWidth}" height="${swatchHeight - 40}" rx="12" fill="${hex}" />
        <rect x="${x}" y="${y + swatchHeight - 40}" width="${swatchWidth}" height="32" rx="6" fill="#F8FAFC" />
        <text x="${x + swatchWidth / 2}" y="${y + swatchHeight - 19}" font-family="Inter, sans-serif" font-size="12" font-weight="600" fill="#1E293B" text-anchor="middle">${hex}</text>
      </g>
    `;
  }).join('');

  return `<?xml version="1.0" encoding="utf-8"?>
<svg xmlns="http://www.w3.org/200svg" width="${totalWidth}" height="${totalHeight}" viewBox="0 0 ${totalWidth} ${totalHeight}">
  <rect width="100%" height="100%" fill="#FFFFFF" rx="16"/>
  <text x="${padding}" y="${padding + 22}" font-family="Inter, sans-serif" font-size="16" font-weight="700" fill="#0F172A">${paletteName || 'Chromapick Palette'}</text>
  ${rects}
</svg>`;
}

/**
 * Exports a PNG Swatch card using offscreen canvas
 */
export async function exportPalettePng(paletteName, colors) {
  return new Promise((resolve) => {
    const swatchWidth = 140;
    const swatchHeight = 180;
    const padding = 32;
    const gap = 16;
    const count = colors.length;
    const totalWidth = count * swatchWidth + (count - 1) * gap + padding * 2;
    const totalHeight = swatchHeight + padding * 2 + 70;

    const canvas = document.createElement('canvas');
    canvas.width = totalWidth;
    canvas.height = totalHeight;
    const ctx = canvas.getContext('2d');

    // Background
    ctx.fillStyle = '#FFFFFF';
    ctx.beginPath();
    ctx.roundRect(0, 0, totalWidth, totalHeight, 20);
    ctx.fill();

    // Title
    ctx.fillStyle = '#0F172A';
    ctx.font = 'bold 22px Inter, sans-serif';
    ctx.fillText(paletteName || 'Chromapick Palette', padding, padding + 26);

    ctx.fillStyle = '#64748B';
    ctx.font = '13px Inter, sans-serif';
    ctx.fillText('Generated by Chromapick — Image Color Extractor & Palette Studio', padding, padding + 48);

    // Swatches
    colors.forEach((c, idx) => {
      const hex = (typeof c === 'string' ? c : c.hex).toUpperCase();
      const x = padding + idx * (swatchWidth + gap);
      const y = padding + 68;

      // Color Box
      ctx.fillStyle = hex;
      ctx.beginPath();
      ctx.roundRect(x, y, swatchWidth, swatchHeight - 48, 12);
      ctx.fill();

      // Border
      ctx.strokeStyle = '#E2E8F0';
      ctx.lineWidth = 1;
      ctx.stroke();

      // Label background
      ctx.fillStyle = '#F8FAFC';
      ctx.beginPath();
      ctx.roundRect(x, y + swatchHeight - 40, swatchWidth, 36, 8);
      ctx.fill();

      // Label text
      ctx.fillStyle = '#0F172A';
      ctx.font = 'bold 13px monospace';
      ctx.textAlign = 'center';
      ctx.fillText(hex, x + swatchWidth / 2, y + swatchHeight - 17);
    });

    canvas.toBlob((blob) => {
      if (blob) {
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${(paletteName || 'chromapick-palette').toLowerCase().replace(/\s+/g, '-')}.png`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(() => URL.revokeObjectURL(url), 1000);
      }
      resolve();
    }, 'image/png');
  });
}

